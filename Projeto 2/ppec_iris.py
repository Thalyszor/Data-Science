RANDOM_STATE = 42

def aplicar_mixup(df, coluna_alvo="class", n_amostras_novas=850, alpha=0.2, random_state=RANDOM_STATE):
    rng = np.random.default_rng(random_state)
    X = df.drop(columns=[coluna_alvo]).values
    y = df[coluna_alvo].values

    novas_X, novas_y = [], []
    for _ in range(n_amostras_novas):
        i, j = rng.integers(0, len(df), size=2)
        lam = rng.beta(alpha, alpha)
        x_novo = lam * X[i] + (1 - lam) * X[j]
        y_novo = y[i] if lam >= 0.5 else y[j]
        novas_X.append(x_novo)
        novas_y.append(y_novo)

    df_novos = pd.DataFrame(novas_X, columns=df.drop(columns=[coluna_alvo]).columns)
    df_novos[coluna_alvo] = novas_y

    return pd.concat([df, df_novos], ignore_index=True)

def inserir_ruido_gaussiano(df, proporcao, coluna_alvo="class", random_state=RANDOM_STATE):
    rng = np.random.default_rng(random_state)
    df_ruidoso = df.copy()

    colunas_numericas = df.select_dtypes(include=[np.number]).columns.tolist()
    colunas_numericas = [c for c in colunas_numericas if c != coluna_alvo]

    for col in colunas_numericas:
        desvio_padrao = df[col].std()
        ruido = rng.normal(loc=0.0, scale=desvio_padrao * proporcao, size=len(df))
        df_ruidoso[col] = df[col] + ruido

    return df_ruidoso

