    plotar_artefatos_xgboost(X_train, X_test, y_train, y_test)

    print("== EXPLICABILIDADE =========================================")
    plotar_shap(df, coluna_alvo)
    plotar_lime(df, indice_amostra=0, coluna_alvo=coluna_alvo)

