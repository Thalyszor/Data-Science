# MODELOS
COLUNA_ALVO  = "class"

def preparar_dados(df, coluna_alvo=COLUNA_ALVO):
    X = df.drop(columns=[coluna_alvo])
    y = df[coluna_alvo]
    le = LabelEncoder()
    y_enc = le.fit_transform(y)
    return X, y_enc, le

def definir_modelos():
    return {
        "Regressão Logística": LogisticRegression(max_iter=1000, random_state=RANDOM_STATE),
        "KNN":                 KNeighborsClassifier(),
        "Decision Tree":       DecisionTreeClassifier(random_state=RANDOM_STATE),
        "Random Forest":       RandomForestClassifier(random_state=RANDOM_STATE),
        "XGBoost":             XGBClassifier(eval_metric="mlogloss", random_state=RANDOM_STATE),
    }

def separar_dados(df, coluna_alvo=COLUNA_ALVO):
    X, y, le = preparar_dados(df, coluna_alvo)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, stratify=y, random_state=RANDOM_STATE
    )
    return X_train, X_test, y_train, y_test, le

def avaliar_modelos(df, coluna_alvo=COLUNA_ALVO, k=5):
    X, y, le = preparar_dados(df, coluna_alvo)
    modelos   = definir_modelos()
    cv        = StratifiedKFold(n_splits=k, shuffle=True, random_state=RANDOM_STATE)
    resultados = []

    fig_cm, eixos = plt.subplots(1, len(modelos), figsize=(6.5 * len(modelos), 4.5), gridspec_kw={'wspace': 0.6})
    fig_roc, ax_roc = plt.subplots(figsize=(8, 4))

    for idx, (nome, modelo) in enumerate(modelos.items()):
        y_pred = cross_val_predict(modelo, X, y, cv=cv)
        y_prob = cross_val_predict(modelo, X, y, cv=cv, method="predict_proba")

        f1      = f1_score(y, y_pred, average="weighted")
        auc_roc = roc_auc_score(y, y_prob, multi_class="ovr", average="weighted")
        acc     = accuracy_score(y, y_pred)

        resultados.append({"Modelo": nome, "F1-Score": f1,
                            "AUC-ROC": auc_roc, "Acurácia": acc})

        # Matriz de confusão
        cm = confusion_matrix(y, y_pred)

        # O truque para a caixa ficar menor dentro do subgráfico:
        # Usamos o parâmetro ax=eixos[idx] e depois ajustamos a posição interna
        disp = ConfusionMatrixDisplay(cm, display_labels=le.classes_)
        disp.plot(ax=eixos[idx], colorbar=False)

        # ALTERAÇÃO 1: Deixa os quadrados menores dentro do espaço disponível
        eixos[idx].set_box_aspect(1) # Força a caixa a ser perfeitamente quadrada

        # ALTERAÇÃO 2: Aumenta o tamanho da fonte do título do modelo
        eixos[idx].set_title(nome, fontsize=14, pad=10)

        # ALTERAÇÃO 3: Aumenta o tamanho dos rótulos dos eixos (Iris-setosa, etc)
        eixos[idx].tick_params(axis='both', which='major', labelsize=12)
        eixos[idx].xaxis.label.set_size(12)
        eixos[idx].yaxis.label.set_size(12)

        # Opcional: Oculta o rótulo do eixo Y a partir do segundo gráfico para limpar o visual
        if idx > 0:
            eixos[idx].set_ylabel('')

        # Curva ROC (OvR para multiclasse)
        for i, classe in enumerate(le.classes_):
            fpr, tpr, _ = roc_curve((y == i).astype(int), y_prob[:, i])
            ax_roc.plot(fpr, tpr, label=f"{nome} – {classe} (AUC={auc(fpr,tpr):.2f})")

    ax_roc.plot([0,1],[0,1],"k--")
    ax_roc.set_xlabel("FPR"); ax_roc.set_ylabel("TPR")
    ax_roc.set_title("Curvas ROC"); ax_roc.legend(fontsize=7)
    plt.tight_layout(); plt.show()

    return pd.DataFrame(resultados).set_index("Modelo")

def plotar_correlacao(df, coluna_alvo=COLUNA_ALVO):
    numericas = df.drop(columns=[coluna_alvo]).select_dtypes(include=[np.number])
    plt.figure(figsize=(7, 5))
    sns.heatmap(numericas.corr(), annot=True, fmt=".2f", cmap="coolwarm")
    plt.title("Matriz de Correlação"); plt.tight_layout(); plt.show()

def plotar_shap(df, coluna_alvo=COLUNA_ALVO):
    """
    Gera SHAP summary plot usando Random Forest como modelo base.
    Registra os 10 atributos mais relevantes.
    """
    X, y, _ = preparar_dados(df, coluna_alvo)
    modelo = RandomForestClassifier(random_state=RANDOM_STATE).fit(X, y)
    explainer   = shap.TreeExplainer(modelo)
    shap_values = explainer.shap_values(X)
    shap.summary_plot(shap_values, X, plot_type="bar", max_display=10)

def plotar_lime(df, indice_amostra=0, coluna_alvo=COLUNA_ALVO):
    """
    Gera explicação LIME para uma amostra específica.
    Parâmetro indice_amostra define qual linha do dataset será explicada.
    """
    X, y, le = preparar_dados(df, coluna_alvo)
    modelo = RandomForestClassifier(random_state=RANDOM_STATE).fit(X, y)
    explainer = lime_tabular.LimeTabularExplainer(
        X.values,
        feature_names=X.columns.tolist(),
        class_names=le.classes_,
        discretize_continuous=True,
        random_state=RANDOM_STATE,
    )
    exp = explainer.explain_instance(
        X.values[indice_amostra], modelo.predict_proba, num_features=10
    )
    exp.show_in_notebook(show_table=True)

