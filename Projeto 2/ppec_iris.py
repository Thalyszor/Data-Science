def plotar_fronteira_knn(X_train, X_test, y_train, y_test, le, n_vizinhos=5):
    pca     = PCA(n_components=2, random_state=RANDOM_STATE)
    Xtr_2d  = pca.fit_transform(X_train)
    Xte_2d  = pca.transform(X_test)
    var     = pca.explained_variance_ratio_
    label_pc1 = f"PC1 ({var[0]:.1%} da variância)"
    label_pc2 = f"PC2 ({var[1]:.1%} da variância)"

    modelo  = KNeighborsClassifier(n_neighbors=n_vizinhos).fit(Xtr_2d, y_train)

    h = 0.05
    x_min, x_max = Xtr_2d[:, 0].min() - 0.5, Xtr_2d[:, 0].max() + 0.5
    y_min, y_max = Xtr_2d[:, 1].min() - 0.5, Xtr_2d[:, 1].max() + 0.5
    xx, yy = np.meshgrid(np.arange(x_min, x_max, h),
                         np.arange(y_min, y_max, h))
    Z = modelo.predict(np.c_[xx.ravel(), yy.ravel()]).reshape(xx.shape)

    plt.figure(figsize=(8, 5))
    plt.contourf(xx, yy, Z, alpha=0.3, cmap="tab10")
    scatter = plt.scatter(Xte_2d[:, 0], Xte_2d[:, 1],
                          c=y_test, cmap="tab10", edgecolors="k", s=40)
    plt.legend(handles=scatter.legend_elements()[0], labels=list(le.classes_))
    plt.title(f"Fronteira de Decisão – KNN (k={n_vizinhos})\n"
              f"Variância total explicada: {sum(var):.1%}")
    plt.xlabel(label_pc1); plt.ylabel(label_pc2)
    plt.tight_layout(); plt.show()

def plotar_arvore(X_train, X_test, y_train, y_test, le, max_depth=2):
    modelo = DecisionTreeClassifier(
        max_depth=max_depth, random_state=RANDOM_STATE
    ).fit(X_train, y_train)
    acc_train = accuracy_score(y_train, modelo.predict(X_train))
    acc_test  = accuracy_score(y_test,  modelo.predict(X_test))
